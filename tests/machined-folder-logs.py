class TestTheWholeTreeMode:
    def run(self, cwd, *args):
        return subprocess.run(
            ["python3", str(SCRIPT), *args], cwd=str(cwd), capture_output=True, text=True
        )

    def test_it_works_without_a_docs_folder(self, tmp_path):
        write(tmp_path / "src/app.py", '"""The app."""\n')
        write(tmp_path / "src/README.md", LOG)
        assert self.run(tmp_path, "--tree", "--check").returncode == 1, "a fresh block is stale"
        assert self.run(tmp_path, "--tree", "--write").returncode == 0
        result = self.run(tmp_path, "--tree", "--check")
        assert result.returncode == 0, result.stdout + result.stderr
        assert "The app." in (tmp_path / "src/README.md").read_text(encoding="utf-8")

    def test_a_new_file_makes_its_folder_log_stale(self, tmp_path):
        write(tmp_path / "README.md", LOG)
        assert self.run(tmp_path, "--tree", "--write").returncode == 0
        write(tmp_path / "later.py", '"""Added after."""\n')
        result = self.run(tmp_path, "--tree", "--check")
        assert result.returncode == 1
        assert "README.md" in result.stdout, "the stale file is not named"

    def test_a_tree_with_no_block_does_not_pass(self, tmp_path):
        write(tmp_path / "README.md", "# Nothing generated here\n")
        result = self.run(tmp_path, "--tree", "--check")
        assert result.returncode == 1
        assert "no auto-index block" in result.stdout.lower()


class TestTheWorkflowChainHoldsTogether:
    """Three files in two places, any of which can drift from the others."""

    def test_the_action_runs_the_generator_over_the_whole_tree(self):
        action = (ROOT / "actions/update-indexes/action.yml").read_text(encoding="utf-8")
        assert "scripts/update-doc-indexes.py" in action
        assert "--tree" in action, "the action would only ever see docs/"

    def test_the_count_the_action_reads_is_the_one_the_script_prints(self, tmp_path):
        """The action counts rewritten files by the lines the script prefixes
        with 📝, so a reworded message would report every run as a no-op."""
        action = (ROOT / "actions/update-indexes/action.yml").read_text(encoding="utf-8")
        assert "'^📝 '" in action
        write(tmp_path / "README.md", LOG)
        result = subprocess.run(
            ["python3", str(SCRIPT), "--tree", "--write"], cwd=str(tmp_path), capture_output=True, text=True
        )
        assert "📝 README.md" in result.stdout.splitlines()

    def test_the_workflow_regenerates_then_proposes_a_pull_request(self):
        doc = load_yaml(".github/workflows/auto-index.yml")
        job = doc["jobs"]["index"]
        uses = [step.get("uses", "") for step in job["steps"]]
        assert any("/actions/update-indexes@" in u for u in uses)
        assert any("/actions/open-pr@" in u for u in uses), "indexes would be regenerated and dropped"
        assert job["permissions"] == {"contents": "write", "pull-requests": "write"}

    def test_the_documented_stub_asks_for_what_the_job_needs(self):
        header = (ROOT / ".github/workflows/auto-index.yml").read_text(encoding="utf-8").split("\n# ---\n", 1)[0]
        assert "contents: write" in header and "pull-requests: write" in header
